export const getFileIcon = (filename: string) => {
    const ext = filename.split('.').pop()?.toLowerCase();
    if (ext === 'docs' || ext === 'doc' || ext === 'docx') {
        return <WordIcon />;
    } else if (ext === 'pdf') {
        return <PdfIcon />;
    } else {
        return <LucideImage className="size-5 text-black" />;
    }
};
